const FILL_ATTR =
  /fill="(#[0-9A-Fa-f]{3,8}|black|#000000?|rgb\([^"]*\)|hsl\([^"]*\)|[^"]+)"/gi;
const STROKE_ATTR =
  /stroke="(#[0-9A-Fa-f]{3,8}|black|#000000?|rgb\([^"]*\)|hsl\([^"]*\)|[^"]+)"/gi;

function extractDistinctFills(content) {
  const fills = new Set();
  for (const match of content.matchAll(FILL_ATTR)) {
    const value = match[1].toLowerCase();
    if (value !== "none" && value !== "currentcolor") {
      fills.add(value);
    }
  }
  return fills;
}

function normalizeSvgContent(content) {
  const distinctFills = extractDistinctFills(content);
  const isMultiColor = distinctFills.size > 1;

  let normalized = content
    .replace(/\sfill="none"/gi, "")
    .replace(/\sfill='none'/gi, "")
    .replace(STROKE_ATTR, 'stroke="currentColor"')
    .replace(FILL_ATTR, 'fill="currentColor"');

  normalized = normalized.replace(/<path(?![^>]*\bfill=)/gi, '<path fill="currentColor"');
  normalized = normalized.replace(/<circle(?![^>]*\bfill=)/gi, '<circle fill="currentColor"');
  normalized = normalized.replace(/<rect(?![^>]*\bfill=)/gi, '<rect fill="currentColor"');
  normalized = normalized.replace(/<polygon(?![^>]*\bfill=)/gi, '<polygon fill="currentColor"');

  if (!/<svg[^>]*\bfill=/i.test(normalized)) {
    normalized = normalized.replace(/<svg/i, '<svg fill="currentColor"');
  }

  return { normalized, isMultiColor };
}

function escapeTemplateLiteral(str) {
  return str.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

const files = fs
  .readdirSync(SVG_DIR)
  .filter((f) => f.endsWith(".svg"))
  .sort();

const inlineEntries = [];
const brandEntries = [];
const scaleEntries = [];

for (const file of files) {
  const slug = file.replace(/\.svg$/, "");
  const filePath = path.join(SVG_DIR, file);
  const original = fs.readFileSync(filePath, "utf8");
  const { normalized, isMultiColor } = normalizeSvgContent(original);

  fs.writeFileSync(filePath, normalized);

  const brand =
    isMultiColor || BRAND_HEX[slug] === undefined
      ? isMultiColor
        ? null
        : (BRAND_HEX[slug] ?? null)
      : BRAND_HEX[slug];

  if (brand) {
    brandEntries.push(`  "${slug}": "${brand}",`);
  } else if (BRAND_HEX[slug] === null || isMultiColor) {
    brandEntries.push(`  "${slug}": null,`);
  }

  const scale = OPTICAL_SCALE[slug];
  if (scale && scale !== 1) {
    scaleEntries.push(`  "${slug}": ${scale},`);
  }

  inlineEntries.push(`  "${slug}": \`${escapeTemplateLiteral(normalized)}\`,`);
  console.log("normalized", file, isMultiColor ? "(multi→mono)" : "");
}

const output = `/** Generated by scripts/normalize-tech-svgs.mjs - do not edit manually */
export const TECH_SVG_INLINE: Record<string, string> = {
${inlineEntries.join("\n")}
};

export const TECH_LOGO_BRAND_COLORS: Record<string, string | null> = {
${brandEntries.join("\n")}
};

export const TECH_LOGO_OPTICAL_SCALE: Record<string, number> = {
${scaleEntries.join("\n")}
};
`;

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, output);
